package fr.insa.ms.Temperature.models;

public class Temperature {
	
	private int valeur;
	
	public Temperature() {}
	
	public Temperature(int valeur) {
		this.valeur = valeur;
	}
	
	public int getValeur() {
		return this.valeur;
	}
	
	public void setValeur(int valeur) {
		this.valeur = valeur;
	}
	
}